const PREF_KEYS = ['domain', 'difficulty', 'team_type', 'team_size', 'time_weeks', 'budget_usd', 'preferred_technologies', 'skills_to_improve', 'career_target', 'orientation', 'deployment_preference', 'hardware_available']
const prefsOf = (p) => Object.fromEntries(PREF_KEYS.map((k) => [k, p[k]]))

export async function owned(req, id) {
  const p = await Project.findById(id)
  if (!p || String(p.user_id) !== String(req.user._id)) throw notFound('Project')
  return p
}
const storeScore = (project, sc, analysisId = null) =>
  ProjectScore.create({ project_id: project._id, analysis_id: analysisId, scores: sc.scores, explanations: sc.explanations, overall: sc.overall, novelty_verified: sc.novelty_verified, methodology: METHOD_VERSION })

export async function recommend(req, res) {
  const uid = req.user._id
  const { budget_currency: cur, ...rest } = req.body
  const pref = await ProjectPreference.create({ user_id: uid, ...rest, budget_usd: cur === 'INR' ? rest.budget_usd / env.inrPerUsd : rest.budget_usd, budget_amount: rest.budget_usd, budget_currency: cur })
  const { ranked, origin, error } = await recommendation.generate(profileOf(req.user), prefsOf(pref), 6, uid)
  const batch = recommendation.newBatchId()
  const out = []
  for (const r of ranked) {
    const p = await Project.create({ user_id: uid, title: r.idea.title, short_description: r.idea.short_description, domain: r.idea.domain, difficulty: r.idea.difficulty, source: 'recommended', origin: origin === 'mixed' ? 'template' : origin, data: r.idea })
    await storeScore(p, r.score)
    await ProjectRecommendation.create({ user_id: uid, preference_id: pref._id, project_id: p._id, batch, rank: r.rank })
    out.push([r.rank, p])
  }
  const notice = error || (origin === 'llm' ? 'Ideas generated by the configured LLM; scores computed by the transparent scoring formula.' : 'No AI key configured: showing ranked built-in template ideas. Add AI_API_KEY for personalised generation.')
  const outs = await projectsOut(out.map(([, p]) => p), uid)
  res.json({ batch, origin, notice, projects: outs.map((o, i) => ({ ...o, rank: out[i][0] })) })
}

export async function latestRecommendations(req, res) {
  const last = await ProjectRecommendation.findOne({ user_id: req.user._id }).sort({ _id: -1 }).lean()
  if (!last) return res.json({ batch: null, projects: [] })
  const recs = await ProjectRecommendation.find({ batch: last.batch, user_id: req.user._id }).sort({ rank: 1 }).lean()
  const projects = new Map((await Project.find({ _id: { $in: recs.map((r) => r.project_id) } })).map((p) => [String(p._id), p]))
  const list = recs.map((r) => projects.get(String(r.project_id))).filter(Boolean)
  const outs = await projectsOut(list, req.user._id)
  res.json({ batch: last.batch, projects: outs.map((o, i) => ({ ...o, rank: recs[i].rank })) })
}

export async function analyze(req, res) {
  const { project_id, idea_text, title, domain } = req.body
  const uid = req.user._id
  let project, text
  if (project_id) {
    project = await owned(req, project_id)
    text = idea_text || `${project.title}. ${project.short_description}. ${(project.data?.ai_ml_components || []).join(' ')}`
  } else if (idea_text) {
    text = idea_text
    project = await Project.create({ user_id: uid, title: (title || idea_text.slice(0, 80)).trim(), short_description: idea_text, domain: domain || 'General', source: 'user_idea', origin: 'user', data: { short_description: idea_text, domain: domain || 'General' } })
  } else throw new HttpError(422, 'Provide idea_text or project_id')

  const r = await analyzeIdea(text, project.domain, uid)
  const m = r.metrics
  const analysis = await ProjectAnalysis.create({
    project_id: project._id, user_id: uid, idea_text: text, concepts: r.concepts, existing_similarity: m.existing_similarity, novelty_score: m.novelty_score, confidence: m.confidence,
    summary: { ...r.gaps, similarity_explanation: m.similarity_explanation, absent_concepts: m.absent_concepts, methodology: m.methodology, disclaimer: r.disclaimer, errors: r.errors,
      corpus_matches: r.corpus.matches, corpus_search: r.corpus.via },
    sources_status: r.sources_status, embedding_backend: r.embedding_backend, suggestion_origin: r.suggestion_origin,
  })
  const repos = r.items.filter((i) => i.kind === 'repo'), papers = r.items.filter((i) => i.kind !== 'repo')
  await SimilarProject.insertMany(repos.map((it) => ({ analysis_id: analysis._id, source: it.source, title: it.title.slice(0, 500), url: it.url.slice(0, 1000), description: it.description, published_at: it.published, extra: { stars: it.stars, ...(it.extra || {}) }, similarity: it.similarity, embedding: it.embedding })))
  await ResearchPaper.insertMany(papers.map((it) => ({ analysis_id: analysis._id, source: it.source, title: it.title.slice(0, 600), url: it.url.slice(0, 1000), abstract: it.description, authors: it.authors, venue: (it.venue || '').slice(0, 300), published_at: it.published, citations: it.citations, similarity: it.similarity, embedding: it.embedding })))
  if (project.source === 'user_idea') { project.data = { ...project.data, technologies: r.concepts.slice(0, 5), innovation_opportunities: r.gaps.improvements.slice(0, 5).map((i) => i.title) }; project.markModified('data'); await project.save() }
  const sc = scoreProject(project.data, profileOf(req.user), null, { novelty_score: m.novelty_score, existing_similarity: m.existing_similarity, confidence: m.confidence })
  await storeScore(project, sc, analysis._id)
  res.json({ project: await projectOut(project, uid), analysis: await analysisOut(analysis) })
}

export async function improve(req, res) {
  const uid = req.user._id
  const project = await owned(req, req.body.project_id)
  const a = await ProjectAnalysis.findOne({ project_id: project._id }).sort({ _id: -1 }).lean()
  let gaps = a ? Object.fromEntries(['improvements', 'missing_features', 'research_gaps'].filter((k) => a.summary?.[k]).map((k) => [k, a.summary[k]])) : null
  if (!gaps || !gaps.improvements?.length) { // 2.0: fall back to the differentiation suggestions when no legacy analysis exists
    const intel = await ProjectIntelligence.findOne({ project_id: project._id }).lean()
    const sug = intel?.differentiation?.suggestions || []
    if (sug.length >= 1) gaps = { improvements: sug.slice(0, 6).map((s) => ({ title: s.feature, category: 'differentiation', rationale: s.why })) }
  }
  const { data, origin, error } = await innovation.improve({ title: project.title, data: project.data }, gaps && Object.keys(gaps).length ? gaps : null, uid)
  const d = project.data || {}
  const newData = { ...d, short_description: data.improved_description, problem_statement: data.problem_statement || d.problem_statement || '', technologies: data.technologies.length ? data.technologies : d.technologies || [],
    modules: data.modules.length ? data.modules : d.modules || [], ai_ml_components: data.ai_ml_components.length ? data.ai_ml_components : d.ai_ml_components || [], innovation_opportunities: data.innovation_opportunities, estimated_weeks: data.estimated_weeks, improvement_of: String(project._id) }
  const imp = await Project.create({ user_id: uid, parent_id: project._id, title: data.improved_title, short_description: data.improved_description, domain: project.domain, difficulty: project.difficulty, source: 'improved', origin, version: project.version + 1, data: newData })
  await storeScore(imp, scoreProject(newData, profileOf(req.user)))
  res.json({ original: await projectOut(project, uid), improved: await projectOut(imp, uid), added_features: data.added_features, origin, notice: error })
}

export async function compare(req, res) {
  const ids = [...new Set(req.body.project_ids)]
  if (ids.length < 2) throw new HttpError(422, 'Select at least two different projects')
  const rows = []
  const intelMap = new Map((await ProjectIntelligence.find({ project_id: { $in: ids } }).lean()).map((i) => [String(i.project_id), i]))
  for (const id of ids) {
    const p = await owned(req, id)
    const out = await projectOut(p, req.user._id)
    const d = p.data || {}, sc = out.scores?.scores || {}
    const intel = intelMap.get(String(p._id))
    const sc2 = sc, tech = technicalComplexity(d), industry = Math.round(0.6 * (sc2.market_potential ?? 0) + 0.4 * (sc2.career_relevance ?? 0))
    const qf = intel?.quality?.final ?? null
    rows.push({ id: String(p._id), title: p.title,
      github_similarity: intel?.github?.summary?.closest?.similarity ?? null, industry, portfolio_value: intel?.quality?.components?.portfolio_value?.score ?? Math.round(0.35 * (sc2.career_relevance ?? 0) + 0.25 * (sc2.novelty ?? 0) + 0.25 * tech + 0.15 * industry),
      portfolio_estimated: !intel?.quality, projectforge_score: qf, cost_level: (d.estimated_cost_usd ?? 0) <= 50 ? 'Low' : (d.estimated_cost_usd ?? 0) <= 300 ? 'Medium' : 'High', reality_status: intel?.reality_check?.status ?? null, novelty: sc.novelty ?? null, novelty_verified: out.scores?.novelty_verified || false, difficulty: sc.difficulty ?? null, cost_usd: d.estimated_cost_usd ?? null, time_weeks: d.estimated_weeks ?? null,
      required_skills: d.required_skills || [], career_value: sc.career_relevance ?? null, research_potential: sc.research_potential ?? null, market_potential: sc.market_potential ?? null,
      ai_complexity: technicalComplexity(d), deployment_complexity: deploymentComplexity(d), overall: out.scores?.overall ?? null })
  }
  // Recommendation: highest ProjectForge Score when analysed, otherwise the existing overall score; explain with the metrics where it leads.
  const key = (r) => r.projectforge_score ?? r.overall ?? 0
  const best = [...rows].sort((a, b) => key(b) - key(a))[0]
  const lead = [['novelty', 'novelty'], ['research_potential', 'research potential'], ['career_value', 'career value'], ['market_potential', 'market potential'], ['portfolio_value', 'portfolio value']]
    .filter(([k]) => best[k] != null && rows.every((r) => r === best || (r[k] ?? -1) <= best[k])).map(([, l]) => l).slice(0, 3)
  const basis = best.projectforge_score != null ? `ProjectForge Score ${best.projectforge_score}` : `overall score ${best.overall} (run the novelty analysis for a full ProjectForge Score)`
  const recommended = { id: best.id, title: best.title, reason: `${best.title} has the highest ${basis}${lead.length ? ` and leads on ${lead.join(', ')}` : ''}.` }
  res.json({ projects: rows, recommended })
}

export async function roadmap(req, res) {
  const p = await owned(req, req.body.project_id)
  const lastPref = await ProjectPreference.findOne({ user_id: req.user._id }).sort({ _id: -1 }).lean()
  const { data, origin, error } = await roadmapSvc.generateRoadmap({ title: p.title, data: p.data }, req.user._id, { teamSize: lastPref?.team_size || 1 })
  await Roadmap.create({ project_id: p._id, data, origin })
  res.json({ project_id: String(p._id), roadmap: data, origin, notice: error })
}
