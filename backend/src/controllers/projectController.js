export async function documentation(req, res) {
  const p = await owned(req, req.body.project_id)
  const a = await ProjectAnalysis.findOne({ project_id: p._id }).sort({ _id: -1 })
  const aOut = a ? await analysisOut(a) : null
  const sources = aOut ? [...aOut.similar_projects.slice(0, 5).map((s) => ({ ...s, authors: [] })), ...aOut.research_papers.slice(0, 8)] : []
  const { data, origin, error } = await generateDocumentation({ title: p.title, data: p.data }, aOut, sources, req.user._id)
  await Document.create({ project_id: p._id, doc_type: 'documentation', content: data, origin })
  res.json({ project_id: String(p._id), documentation: data, origin, notice: error })
}

const escapeRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
export async function list(req, res) {
  const uid = req.user._id
  const { q = '', domain = '', scope = 'all' } = req.query
  if (!['all', 'saved', 'favorites', 'recommended', 'analyzed'].includes(scope)) throw new HttpError(422, 'Invalid scope')
  const filter = { user_id: uid }
  if (q) filter.$or = [{ title: new RegExp(escapeRe(String(q)), 'i') }, { short_description: new RegExp(escapeRe(String(q)), 'i') }]
  if (domain) filter.domain = String(domain)
  if (scope === 'saved') filter._id = { $in: (await SavedProject.find({ user_id: uid }).select('project_id').lean()).map((x) => x.project_id) }
  else if (scope === 'favorites') filter._id = { $in: (await Favorite.find({ user_id: uid }).select('project_id').lean()).map((x) => x.project_id) }
  else if (scope === 'recommended') filter.source = { $in: ['recommended', 'seed_demo'] }
  else if (scope === 'analyzed') filter._id = { $in: await ProjectAnalysis.distinct('project_id', { user_id: uid }) }
  res.json({ projects: await projectsOut(await Project.find(filter).sort({ updated_at: -1 }).limit(200), uid) })
}

export const get = async (req, res) => res.json(await projectOut(await owned(req, req.params.id), req.user._id, { detail: true }))

export async function remove(req, res) {
  const p = await owned(req, req.params.id)
  const analyses = await ProjectAnalysis.find({ project_id: p._id }).select('_id').lean()
  const aIds = analyses.map((a) => a._id)
  await Promise.all([
    SimilarProject.deleteMany({ analysis_id: { $in: aIds } }), ResearchPaper.deleteMany({ analysis_id: { $in: aIds } }), ProjectAnalysis.deleteMany({ project_id: p._id }),
    ProjectScore.deleteMany({ project_id: p._id }), Roadmap.deleteMany({ project_id: p._id }), Document.deleteMany({ project_id: p._id }),
    SavedProject.deleteMany({ project_id: p._id }), Favorite.deleteMany({ project_id: p._id }), ProjectRecommendation.deleteMany({ project_id: p._id }),
    Project.updateMany({ parent_id: p._id }, { parent_id: null }),
  ])
  await p.deleteOne()
  res.status(204).end()
}

export async function save(req, res) {
  const p = await owned(req, req.params.id)
  await SavedProject.updateOne({ user_id: req.user._id, project_id: p._id }, { $setOnInsert: { user_id: req.user._id, project_id: p._id } }, { upsert: true })
  res.json({ saved: true })
}
export async function unsave(req, res) {
  const p = await owned(req, req.params.id)
  await SavedProject.deleteOne({ user_id: req.user._id, project_id: p._id })
  res.json({ saved: false })
}
export async function toggleFavorite(req, res) {
  const p = await owned(req, req.params.id)
  const del = await Favorite.deleteOne({ user_id: req.user._id, project_id: p._id })
  if (del.deletedCount) return res.json({ favorite: false })
  await Favorite.create({ user_id: req.user._id, project_id: p._id })
  res.json({ favorite: true })
}

export async function exportProject(req, res) {
  const format = req.query.format || 'md'
  if (!['md', 'html', 'json'].includes(format)) throw new HttpError(422, 'format must be md, html or json')
  const p = await owned(req, req.params.id)
  const d = await projectOut(p, req.user._id, { detail: true })
  const name = `project-${p._id}.${format}`
  res.set('Content-Disposition', `attachment; filename="${name}"`)
  if (format === 'json') return res.json(d)
  const text = buildMarkdown(d, d.analysis, d.roadmap?.data, d.architecture?.data, d.documentation?.data)
  if (format === 'html') return res.type('html').send(markdownToHtml(text, p.title))
  res.type('text/markdown').send(text)
}
