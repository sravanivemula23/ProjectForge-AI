import { marked } from 'marked'

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')

export function buildMarkdown(project, analysis, roadmap, architecture, doc) {
  const L = [`# ${project.title}`, '', `*Domain:* ${project.domain} | *Difficulty:* ${project.difficulty}`, '', project.short_description || '', '']
  const sc = project.scores
  if (sc) {
    L.push('## Scores', '', '| Metric | Score |', '|---|---|')
    for (const [k, v] of Object.entries(sc.scores)) L.push(`| ${k.replace(/_/g, ' ').replace(/\b\w/g, (c) => c.toUpperCase())} | ${v} |`)
    L.push(`| **Overall** | **${sc.overall}** |`, '', `_Novelty is ${sc.novelty_verified ? 'verified against retrieved sources.' : 'an unverified prior; run a novelty analysis.'}_`, '')
  }
  if (analysis) {
    const s = analysis.summary || {}
    L.push('## Novelty Analysis', '', `Estimated similarity: ${analysis.existing_similarity}%  `, `Estimated novelty: ${analysis.novelty_score}/100 (confidence: ${analysis.confidence})`, '', s.similarity_explanation || '', '')
    for (const [title, key] of [['Common features', 'common_features'], ['Missing features', 'missing_features'], ['Research gaps', 'research_gaps']]) if (s[key]?.length) L.push(`### ${title}`, '', ...s[key].map((x) => `- ${x}`), '')
    if (s.improvements?.length) L.push('### Suggested improvements (AI/template generated)', '', ...s.improvements.map((i) => `- **${i.title}** - ${i.rationale}`), '')
    const srcs = [...analysis.similar_projects.slice(0, 8), ...analysis.research_papers.slice(0, 8)]
    if (srcs.length) L.push('### Verified sources', '', ...srcs.map((x) => `- [${x.title}](${x.url}) (${x.source}, similarity ${x.similarity}%)`), '')
  }
  if (roadmap) {
    L.push('## Roadmap', '')
    for (const p of roadmap.phases) L.push(`### Phase ${p.number}: ${p.name} (${p.estimated_weeks} wk)`, '', ...p.tasks.map((t) => `- ${t}`), `\n*Output:* ${p.expected_output}`, '')
  }
  if (architecture) L.push('## Architecture', '', architecture.system_overview || '', '', ...architecture.layers.map((l) => `- **${l.name}**: ${l.components.join(', ')}`), '')
  if (doc) {
    for (const [k, label] of [['abstract', 'Abstract'], ['introduction', 'Introduction'], ['problem_statement', 'Problem Statement'], ['existing_system', 'Existing System'], ['proposed_system', 'Proposed System'], ['methodology', 'Methodology'], ['conclusion', 'Conclusion']]) if (doc[k]) L.push(`## ${label}`, '', doc[k], '')
    for (const [k, label] of [['objectives', 'Objectives'], ['modules', 'Modules'], ['technologies', 'Technologies'], ['advantages', 'Advantages'], ['limitations', 'Limitations'], ['future_scope', 'Future Scope'], ['references', 'References']]) if (doc[k]?.length) L.push(`## ${label}`, '', ...doc[k].map((x) => `- ${x}`), '')
    L.push('## Resume description', '', doc.resume_description || '', '', '## PPT outline', '', ...(doc.ppt_outline || []).map((x, i) => `${i + 1}. ${x}`), '', '## Viva questions', '', ...(doc.viva_questions || []).map((q) => `**Q:** ${q.question}  \n**A:** ${q.answer}\n`), '## Interview explanation', '', doc.interview_explanation || '', '')
  }
  L.push('---', '_Generated by ProjectForge AI. Novelty values are estimates, not guarantees of uniqueness._')
  return L.join('\n')
}

export const markdownToHtml = (text, title) =>
  `<!doctype html><html><head><meta charset='utf-8'><title>${esc(title)}</title><style>body{font-family:system-ui;max-width:820px;margin:2rem auto;padding:0 1rem;line-height:1.55}table{border-collapse:collapse}td,th{border:1px solid #ccc;padding:.3rem .6rem}</style></head><body>${marked.parse(esc(text))}</body></html>`
